async function insertPublicDocumentMetadata(anonymous, requestId, overrides = {}) {
  const documentId = overrides.id ?? randomUUID();
  const storagePath =
    overrides.storage_path ?? `public-orders/${orgs.company}/${requestId}/${documentId}/security-order.pdf`;

  const row = {
    id: documentId,
    organization_id: orgs.company,
    public_order_request_id: requestId,
    file_name: "security-order.pdf",
    storage_bucket: "public-order-uploads",
    storage_path: storagePath,
    content_type: "application/pdf",
    file_size_bytes: 1024,
    ...overrides
  };

  const { error } = await anonymous.from("public_order_request_documents").insert(row);
  return { error, row };
}

loadLocalEnv();

const supabaseUrl = requiredEnv("NEXT_PUBLIC_SUPABASE_URL", process.env.NEXT_PUBLIC_SUPABASE_URL);
const publishableKey = requiredEnv(
  "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY or NEXT_PUBLIC_SUPABASE_ANON_KEY",
  process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ?? process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
);

const roleDefinitions = {
  companyAdmin: ["Company Admin", "CAS_STAGE_COMPANY_ADMIN_EMAIL", "CAS_STAGE_COMPANY_ADMIN_PASSWORD"],
  officeStaff: ["Office Staff", "CAS_STAGE_OFFICE_STAFF_EMAIL", "CAS_STAGE_OFFICE_STAFF_PASSWORD"],
  appraiser: ["Appraiser", "CAS_STAGE_APPRAISER_EMAIL", "CAS_STAGE_APPRAISER_PASSWORD"],
  reviewer: ["Reviewer", "CAS_STAGE_REVIEWER_EMAIL", "CAS_STAGE_REVIEWER_PASSWORD"],
  amcAdmin: ["AMC Admin", "CAS_STAGE_AMC_ADMIN_EMAIL", "CAS_STAGE_AMC_ADMIN_PASSWORD"],
  clientUser: ["Lender/Client User", "CAS_STAGE_CLIENT_USER_EMAIL", "CAS_STAGE_CLIENT_USER_PASSWORD"]
};

const credentials = Object.fromEntries(
  Object.entries(roleDefinitions).map(([roleKey, [label, emailEnv, passwordEnv]]) => [
    roleKey,
    {
      label,
      email: requiredEnv(emailEnv, process.env[emailEnv]),
      password: requiredEnv(`${passwordEnv} or CAS_STAGE_TEST_PASSWORD`, process.env[passwordEnv] ?? process.env.CAS_STAGE_TEST_PASSWORD)
    }
  ])
);

const orgs = {
  company: "11111111-1111-1111-1111-111111111111",
  amc: "22222222-2222-2222-2222-222222222222",
  client: "33333333-3333-3333-3333-333333333333"
};

const anonymous = createSupabaseClient();
const results = [];

const companyAdmin = await signIn("companyAdmin");
const officeStaff = await signIn("officeStaff");
const appraiser = await signIn("appraiser");
const reviewer = await signIn("reviewer");
const amcAdmin = await signIn("amcAdmin");
const clientUser = await signIn("clientUser");

let publicRequestId = "";
let publicUploadPath = "";

await runCheck(results, "anonymous users cannot invoke privileged functions", async () => {
  await expectRpcDenied(anonymous, "has_permission", { target_organization_id: orgs.company, target_permission: "manage_accounting" }, "Anonymous has_permission");
  await expectRpcDenied(anonymous, "has_any_permission", { target_organization_id: orgs.company, target_permissions: ["manage_accounting"] }, "Anonymous has_any_permission");
  await expectRpcDenied(anonymous, "is_org_member", { target_organization_id: orgs.company }, "Anonymous is_org_member");
  await expectRpcDenied(anonymous, "is_org_admin", { target_organization_id: orgs.company }, "Anonymous is_org_admin");
  await expectRpcDenied(anonymous, "can_read_order", { target_order_id: randomUUID() }, "Anonymous can_read_order");
  await expectRpcDenied(anonymous, "can_read_document", { target_document_id: randomUUID() }, "Anonymous can_read_document");
  await expectRpcDenied(anonymous, "current_organization_id", {}, "Anonymous current_organization_id");
  return "Privileged RPC helpers denied or returned no elevated data.";
});

await runCheck(results, "authenticated non-admin cannot invoke admin helpers directly", async () => {
  await expectRpcDenied(appraiser.client, "is_org_admin", { target_organization_id: orgs.company }, "Appraiser is_org_admin");
  await expectRpcDenied(appraiser.client, "has_permission", { target_organization_id: orgs.company, target_permission: "manage_accounting" }, "Appraiser has_permission");
  await expectRpcDenied(officeStaff.client, "has_permission", { target_organization_id: orgs.company, target_permission: "manage_company_users" }, "Office staff has_permission");
  return "Non-admin direct privileged RPC calls did not expose elevated access.";
});

await runCheck(results, "public users cannot query private tenant data", async () => {
  await expectNoRows(anonymous, "organizations", "Anonymous organizations query");
  await expectNoRows(anonymous, "orders", "Anonymous orders query");
  await expectNoRows(anonymous, "documents", "Anonymous documents query");
  await expectNoRows(anonymous, "payroll_run_items", "Anonymous payroll query");
  return "Private tenant tables returned no rows to anonymous users.";
});

await runCheck(results, "public upload requires an enabled intake and validated metadata", async () => {
  await upsertPublicOrderSettings(companyAdmin);
  publicRequestId = await createAnonymousPublicOrderRequest(anonymous);

  const invalid = await insertPublicDocumentMetadata(anonymous, publicRequestId, {
    storage_path: "public-orders/escape.pdf"
  });
  assert(invalid.error, "Invalid public document metadata path was accepted.");

  const valid = await insertPublicDocumentMetadata(anonymous, publicRequestId);
  failOn(valid.error, "Valid public document metadata insert");
  publicUploadPath = valid.row.storage_path;

  const payload = new Blob(["Phase 10.1 public upload smoke"], { type: "application/pdf" });
  const { error: uploadError } = await anonymous.storage.from("public-order-uploads").upload(publicUploadPath, payload, {
    contentType: "application/pdf"
  });
  failOn(uploadError, "Anonymous upload to validated public-order path");
  return "Only metadata-backed public upload paths were accepted.";
});

await runCheck(results, "public upload cannot list, read, delete, or escape its path", async () => {
  const { data: listData, error: listError } = await anonymous.storage.from("public-order-uploads").list("public-orders", { limit: 1 });
  assert(listError || (listData ?? []).length === 0, "Anonymous user listed public-order upload objects.");

  const { data: downloadData, error: downloadError } = await anonymous.storage.from("public-order-uploads").download(publicUploadPath);
  assert(downloadError || !downloadData, "Anonymous user downloaded a public-order upload.");

  const { data: deleteData, error: deleteError } = await anonymous.storage.from("public-order-uploads").remove([publicUploadPath]);
  assert(deleteError || (deleteData ?? []).length === 0, "Anonymous user deleted a public-order upload.");

  const payload = new Blob(["escape"], { type: "application/pdf" });
  const { error: escapeError } = await anonymous.storage
    .from("public-order-uploads")
    .upload(`public-orders/${orgs.company}/${publicRequestId}/${randomUUID()}/escape.pdf`, payload, { contentType: "application/pdf" });
  assert(escapeError, "Anonymous upload without matching metadata was accepted.");
  return "Anonymous public storage actions are limited to metadata-backed inserts only.";
});

await runCheck(results, "receiving organization can access public upload and cross-org access is denied", async () => {
  const { data: signedUrl, error: signedUrlError } = await companyAdmin.client.storage
    .from("public-order-uploads")
    .createSignedUrl(publicUploadPath, 60);
  failOn(signedUrlError, "Company admin signed URL for public upload");
  assert(signedUrl?.signedUrl, "Company admin did not receive a signed URL for public upload.");

  const { data: crossOrgSignedUrl, error: crossOrgError } = await amcAdmin.client.storage
    .from("public-order-uploads")
    .createSignedUrl(publicUploadPath, 60);
  assert(crossOrgError || !crossOrgSignedUrl?.signedUrl, "Cross-organization user received public upload signed URL.");
  return "Receiving organization access works; cross-organization storage access is denied.";
});

await runCheck(results, "role permissions still allow operational reads", async () => {
  const { error: staffOrderError } = await officeStaff.client.from("orders").select("id").eq("organization_id", orgs.company).limit(1);
  failOn(staffOrderError, "Office staff order read");

  const { error: appraiserOrderError } = await appraiser.client.from("orders").select("id").limit(1);
  failOn(appraiserOrderError, "Appraiser order read");

  const { error: reviewerQueueError } = await reviewer.client.from("report_submissions").select("id").limit(1);
  failOn(reviewerQueueError, "Reviewer queue read");
  return "Office staff, appraiser, and reviewer reads still pass after hardening.";
});

await runCheck(results, "cross-tenant function probes fail", async () => {
  await expectRpcDenied(clientUser.client, "can_read_order", { target_order_id: randomUUID() }, "Client cross-tenant can_read_order");
  await expectRpcDenied(amcAdmin.client, "can_read_document", { target_document_id: randomUUID() }, "AMC cross-tenant can_read_document");
  return "Direct cross-tenant function probes are not usable from client roles.";
});

for (const result of results) {
  console.log(`${result.ok ? "PASS" : "FAIL"} ${result.name}: ${result.detail}`);
}

if (results.some((result) => !result.ok)) {
  process.exit(1);
}
